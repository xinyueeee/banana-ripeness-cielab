EXPECTED_SIZE_HW = (EXPECTED_SIZE[1], EXPECTED_SIZE[0])  # (w, h) for cv2.resize


def prepare_rgb_from_bytes(data: bytes) -> np.ndarray:
    """Decode uploaded bytes to a 416x416 uint8 RGB array.

    Mirrors the notebook's load_native_rgb() decode/resize contract exactly
    (cv2.imdecode COLOR -> BGR2RGB -> INTER_AREA resize when size differs).
    """
    encoded = np.frombuffer(data, dtype=np.uint8)
    if encoded.size == 0:
        raise ValueError("Empty image file.")
    bgr = cv2.imdecode(encoded, cv2.IMREAD_COLOR)
    if bgr is None:
        raise ValueError("Image could not be decoded.")
    rgb = cv2.cvtColor(bgr, cv2.COLOR_BGR2RGB)
    if rgb.shape[:2] != EXPECTED_SIZE:
        rgb = cv2.resize(rgb, EXPECTED_SIZE_HW, interpolation=cv2.INTER_AREA)
    if rgb.shape != (*EXPECTED_SIZE, 3) or rgb.dtype != np.uint8:
        raise ValueError(f"Unexpected prepared array: {rgb.shape}, {rgb.dtype}")
    return rgb


def image_feature_row(rgb: np.ndarray, prototypes: "pd.DataFrame"):
    """Run the frozen pipeline on one RGB image -> (feature_df_20, channels, segmentation).

    Same sequence as notebook cell 10: prepare_cielab_channels -> segment_banana
    -> to_true_lab_units -> extract_lab_features -> add_ciede2000_features.
    Returns feature_df=None if segmentation yields an empty mask (as the notebook does).
    """
    channels = prepare_cielab_channels(rgb)
    segmentation = segment_banana(channels["b8"])
    L, a, b = to_true_lab_units(channels["L8"], channels["a8"], channels["b8"])
    stats = extract_lab_features(L, a, b, segmentation.final_mask)
    if stats is None:
        return None, channels, segmentation
    row = pd.DataFrame([stats])
    enhanced = add_ciede2000_features(row, prototypes)
    feature_df = enhanced[FROZEN_FEATURES].astype(np.float64)
    return feature_df, channels, segmentation
